-- AIDepQuiz Phase 1 content schema.
-- The API is stateless: this migration deliberately does not create attempts
-- or user-result history tables.

drop table if exists options, questions, results cascade;

create table test_versions (
  id BIGINT generated by default as identity primary key,
  test_slug VARCHAR(100) not null,
  test_version VARCHAR(100) not null,
  locale VARCHAR(10) not null,
  title TEXT not null,
  question_count INTEGER not null default 16,
  scale_type VARCHAR(20) not null default 'likert',
  scale_min INTEGER not null default 1,
  scale_max INTEGER not null default 5,
  scoring_method VARCHAR(20) not null default 'mean',
  total_min INTEGER not null default 16,
  total_max INTEGER not null default 80,
  mean_min NUMERIC(3, 2) not null default 1.00,
  mean_max NUMERIC(3, 2) not null default 5.00,
  display_decimals INTEGER not null default 2,
  reverse_scored_items BOOLEAN not null default false,
  is_active BOOLEAN not null default true,
  constraint uq_test_versions_version unique (test_slug, test_version, locale),
  constraint test_version_slug_check check (test_slug = 'ai-dependence'),
  constraint test_version_locale_check check (locale = 'vi-VN'),
  constraint test_version_question_count_check check (question_count = 16),
  constraint test_version_scale_check check (
    scale_type = 'likert'
    and scale_min = 1
    and scale_max = 5
  ),
  constraint test_version_scoring_check check (
    scoring_method = 'mean'
    and total_min = 16
    and total_max = 80
    and mean_min = 1.00
    and mean_max = 5.00
    and display_decimals = 2
    and reverse_scored_items = false
  )
);

create unique index uq_active_test_version
  on test_versions (test_slug, locale)
  where is_active;

create table scale_labels (
  id BIGINT generated by default as identity primary key,
  test_version_id BIGINT not null,
  value INTEGER not null,
  text TEXT not null,
  display_order INTEGER not null,
  constraint fk_scale_label_test_version foreign key (test_version_id)
    references test_versions (id) on delete cascade,
  constraint uq_scale_label_value unique (test_version_id, value),
  constraint uq_scale_label_order unique (test_version_id, display_order),
  constraint scale_label_value_check check (value between 1 and 5),
  constraint scale_label_order_check check (display_order between 1 and 5)
);

create table subscales (
  id BIGINT generated by default as identity primary key,
  test_version_id BIGINT not null,
  subscale_key VARCHAR(20) not null,
  label VARCHAR(150) not null,
  display_order INTEGER not null,
  constraint fk_subscale_test_version foreign key (test_version_id)
    references test_versions (id) on delete cascade,
  constraint uq_subscale_key unique (test_version_id, subscale_key),
  constraint uq_subscale_order unique (test_version_id, display_order),
  constraint uq_subscale_test_version_id unique (test_version_id, id),
  constraint subscale_key_check check (
    subscale_key in ('emotional', 'functional', 'cognitive', 'control')
  ),
  constraint subscale_label_check check (
    (subscale_key = 'emotional' and label = 'Phụ thuộc về cảm xúc')
    or (subscale_key = 'functional' and label = 'Phụ thuộc về chức năng')
    or (subscale_key = 'cognitive' and label = 'Phụ thuộc về nhận thức')
    or (subscale_key = 'control' and label = 'Mất khả năng kiểm soát')
  ),
  constraint subscale_order_check check (display_order between 1 and 4)
);

create table questions (
  id BIGINT generated by default as identity primary key,
  test_version_id BIGINT not null,
  subscale_id BIGINT not null,
  question_id VARCHAR(20) not null,
  content TEXT not null,
  display_order INTEGER not null,
  constraint fk_question_test_version foreign key (test_version_id)
    references test_versions (id) on delete cascade,
  constraint fk_question_subscale foreign key (test_version_id, subscale_id)
    references subscales (test_version_id, id) on delete restrict,
  constraint uq_question_business_id unique (test_version_id, question_id),
  constraint uq_question_order unique (test_version_id, display_order),
  constraint question_id_format_check check (question_id ~ '^dep-[0-9]{2}$'),
  constraint question_order_check check (display_order between 1 and 16)
);

create table options (
  id BIGINT generated by default as identity primary key,
  question_id BIGINT not null,
  option_id VARCHAR(50) not null,
  content TEXT not null,
  score INTEGER not null,
  display_order INTEGER not null,
  constraint fk_option_question_id foreign key (question_id)
    references questions (id) on delete cascade,
  constraint uq_option_business_id unique (question_id, option_id),
  constraint uq_option_question_value unique (question_id, score),
  constraint uq_option_question_display_order unique (question_id, display_order),
  constraint option_score_check check (score between 1 and 5),
  constraint option_display_order_check check (display_order between 1 and 5)
);

create table results (
  id BIGINT generated by default as identity primary key,
  test_version_id BIGINT not null,
  category_key VARCHAR(20) not null,
  label VARCHAR(150) not null,
  min_mean NUMERIC(3, 2) not null,
  max_mean NUMERIC(3, 2) not null,
  description TEXT not null,
  feedback TEXT not null,
  advice JSONB not null,
  limitations JSONB not null,
  constraint fk_result_test_version foreign key (test_version_id)
    references test_versions (id) on delete cascade,
  constraint uq_result_category unique (test_version_id, category_key),
  constraint result_category_key_check check (
    category_key in ('low', 'moderate', 'high')
  ),
  constraint result_category_label_check check (
    (category_key = 'low' and label = 'Thấp')
    or (category_key = 'moderate' and label = 'Trung bình')
    or (category_key = 'high' and label = 'Cao')
  ),
  constraint result_mean_range_check check (
    min_mean between 1.00 and 5.00
    and max_mean between 1.00 and 5.00
    and min_mean <= max_mean
  ),
  constraint result_advice_array_check check (
    case
      when jsonb_typeof(advice) = 'array'
        then jsonb_array_length(advice) between 1 and 3
      else false
    end
  ),
  constraint result_limitations_array_check check (
    case
      when jsonb_typeof(limitations) = 'array'
        then jsonb_array_length(limitations) >= 0
      else false
    end
  ),
  constraint result_category_range_check check (
    (category_key = 'low' and min_mean = 1.00 and max_mean = 2.33)
    or (category_key = 'moderate' and min_mean = 2.34 and max_mean = 3.66)
    or (category_key = 'high' and min_mean = 3.67 and max_mean = 5.00)
  )
);
