create table questions (
  id BIGINT generated by default as identity primary key,
  content TEXT not null,
  display_order INTEGER not null unique
);

alter table questions
add constraint question_display_order check (display_order between 1 and 10);

create table options (
  id BIGINT generated by default as identity primary key,
  question_id BIGINT not null,
  content TEXT not null,
  score INTEGER not null,
  display_order INTEGER not null
);

alter table options
add constraint fk_option_question_id foreign KEY (question_id) references questions (id) on delete CASCADE,
add constraint option_score_check check (score >= 0),
add constraint option_question_display_order_unique unique (question_id, display_order);

create table results (
  id BIGINT generated by default as identity primary key,
  min_score INTEGER not null,
  max_score INTEGER not null,
  level VARCHAR(150) not null,
  evaluation JSONB not null,
  advice JSONB not null
);

alter table results
add constraint result_min_max_score check (min_score <= max_score);
